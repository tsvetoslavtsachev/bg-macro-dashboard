"""
catalog/polarity.py
===================
Полярностни решения за lens health scoring — ЕДИНЕН източник на истина (BG).

Механизмът е портнат от `dashboards/eu-macro-dashboard/catalog/polarity.py`;
методологията е в `dashboards/macro-satellite/LENS_SCORING_METHODOLOGY.md` §3.

Типове:
  +1                        линейна, нагоре = по-здраво (растеж, заплати, доверие)
  −1                        линейна, нагоре = по-нездраво (безработица, лихви)
  ("U", "self")             U около собствената 10-г. норма
  ("U", "target", X)        U около фиксирана цел — инфлацията около X%

Защо U за инфлацията: наивното „ниско = добре" прави дефлацията отличник.
Честният уред мери ОТКЛОНЕНИЕ от целта в двете посоки. От 01.01.2026 България
е в еврозоната → целта е ЕЦБ-целта, същият център като EA.
"""
from __future__ import annotations

from typing import Any

INFLATION_TARGET = 2.0  # % — ЕЦБ цел (БГ е в еврозоната от 01.01.2026)
U_BAND = 1.0            # толерантна лента в σ, преди здравето да падне

POLARITY: dict[str, Any] = {
    # ── GROWTH ────────────────────────────────────────────────────────────────
    "BG_GDP_YOY": +1,
    "BG_INDPRO": +1,
    "BG_CONS": +1,
    "BG_ESI": +1,

    # ── INFLATION (U около целта ~2%) ─────────────────────────────────────────
    "BG_HICP": ("U", "target", INFLATION_TARGET),
    "BG_HICP_CORE": ("U", "target", INFLATION_TARGET),

    # ── LABOR ─────────────────────────────────────────────────────────────────
    "BG_UNRATE": -1,          # висока безработица = нездраво
    # BG_WAGES остава +1 (labor-смисъл: по-силен труд). Двузначността на
    # заплатите в прегряваща икономика е Фаза 3 обсъждане, НЕ решение тук.
    "BG_WAGES": +1,

    # ── EXTERNAL ──────────────────────────────────────────────────────────────
    "BG_CA_GDP": +1,          # по-силен баланс = по-здраво
    "BG_TRADE_GS": +1,        # по-силен търговски баланс = по-здраво

    # ── CREDIT ────────────────────────────────────────────────────────────────
    "BG_LT_RATE": -1,         # по-висока цена на дълга = по-стегнато/стрес
    # Цената на НОВИЯ фирмен кредит (мандат №42): по-скъп кредит = по-стегнати
    # условия за фирмите. Същата посока като доходността, но друг канал —
    # затова живее в СВОЯ peer-група (`lending_cost`), не при `yields`.
    "BG_LENDING_RATE": -1,
    # Заемният ръст = по-силен кредитен цикъл. Двузначността (бърз ръст е и
    # сила, и риск) е СЪЩИЯТ въпрос като при заплатите — решава се във Фаза 3.2
    # заедно с WAGES, не поотделно тук.
    "BG_LOANS_NFC": +1,
    "BG_LOANS_HH": +1,

    # ── PROPERTY (мандат №43) ─────────────────────────────────────────────────
    # И трите са +1 (по-скъпи жилища, повече строителство, повече разрешителни =
    # „по-здраво“ в лещовия смисъл) — и трите са ПОД ПРЕГЛЕД по СЪЩАТА причина
    # като WAGES и заемния ръст: бум в цените и разрешителните е здраве ДНЕС и
    # риск УТРЕ. Трите бум-полярности се решават ЗАЕДНО във Фаза 3.x („бум-
    # полярностите“), не поотделно тук — иначе уредът ще мери едно и също
    # двузначие с различни аршини на различни места.
    "BG_HPI": +1,
    "BG_CONSTR": +1,
    "BG_PERMITS": +1,
}

# Multi-lens override (лещово-специфична полярност). Празно за БГ — всяка серия
# живее в точно една леща. Механизмът се пази заради фамилния паритет.
POLARITY_BY_LENS: dict[tuple[str, str], Any] = {}

# Peer-group тегла. При 10 серии групите са по 1 серия → всички 1.0 (мандат №38
# §А3). Механизмът се пази, за да не се преправя агрегацията при Фаза 3.
PEER_GROUP_WEIGHT: dict[str, float] = {}


def polarity_for(key: str, lens: str | None = None) -> Any:
    """Полярността на серия (по избор — в контекста на конкретна леща)."""
    if lens is not None and (lens, key) in POLARITY_BY_LENS:
        return POLARITY_BY_LENS[(lens, key)]
    return POLARITY.get(key, +1)


def peer_group_weight(pg: str) -> float:
    """Тегло на peer-група в лещата. Default 1.0."""
    return PEER_GROUP_WEIGHT.get(pg, 1.0)


def is_u_shaped(polarity: Any) -> bool:
    """True за U-полярност (лента около цел или около собствената норма)."""
    return isinstance(polarity, tuple) and bool(polarity) and polarity[0] == "U"
