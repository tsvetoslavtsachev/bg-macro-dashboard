"""
catalog/polarity.py
===================
Дефинира посоката (полярността) на сериите.
True  = по-висока стойност е ДОБРЕ за макро резултата (напр. БВП)
False = по-висока стойност е ЗЛЕ за макро резултата (напр. Безработица, Инфлация)
"""
from __future__ import annotations

# Дефинираме кои серии са с обърната логика (високо = зле)
# Ако серия не е тук, по подразбиране е True (високо = добре)
INVERTED_SERIES = {
    # Labor
    "BG_UNRATE",        # Висока безработица = зле
    
    # Inflation
    "BG_HICP",          # Висока инфлация = зле
    "BG_HICP_CORE",     # Висока базисна инфлация = зле
    
    # Credit
    "BG_LT_RATE",       # Висока лихва по дълга = зле
}

def polarity_for(series_key: str) -> bool:
    """
    Връща True ако по-висока стойност е позитивна за икономиката,
    и False ако по-висока стойност е негативна.
    """
    if series_key in INVERTED_SERIES:
        return False
    return True
