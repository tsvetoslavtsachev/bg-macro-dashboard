"""
sources/derived.py
==================
ИЗВЕДЕНИТЕ серии (мандат №54): раждат се от снапшота, не се фетчват.

Класът на серията е нов за този дашборд. Досега всяка серия имаше адрес в чужд
API; тази има РЕЦЕПТА. Затова:
  · `source: "derived"` в каталога — декларация, не източник;
  · никой адаптер не я търси (`build_adapters()` няма такъв ключ);
  · `derive_series` се вика в `run.py::_score_everything` СЛЕД `splice_loans` —
    изведеното стъпва на сплайснатия (дълъг, тримесечен) кредитен сток, иначе
    би мерило само късия прозорец на ЕЦБ портала.

──────────────────────────────────────────────────────────────────────────────
КОНВЕНЦИЯТА на `BG_CREDIT_GDP_HH` (кредит домакинства / БВП)
──────────────────────────────────────────────────────────────────────────────
    ratio(Q) = HH сток в края на тримесечие Q
               ─────────────────────────────────────────── × 100
               сумата на номиналния БВП за Q-3 … Q (4 тримесечия)

Числителят е СТОК (млн. EUR към един момент), знаменателят е ПОТОК (млн. EUR за
период) — затова потокът се анюализира с 4-тримесечна СУМА, не с плъзгаща
средна на темпове. Сумата сама гаси сезонността, което е и причината БВП да се
чете NSA (сезонно изгладеният отгоре би бил второ изглаждане на същото; живо
проверено 29.07.2026 — SCA дава същото ratio до 0.1пп).

Изравняването е по (година, тримесечие), не по дата: двата източника имат
РАЗЛИЧНИ датови конвенции — кредитният сток сяда на ден 1 на ПОСЛЕДНИЯ месец на
тримесечието (2026Q1 → 2026-03-01), а Eurostat тримесечията на ПЪРВИЯ
(2026Q1 → 2026-01-01). Изходната серия носи Eurostat конвенцията, защото
знаменателят е обвързващата съставка: последната ѝ точка НЕ може да изпревари
последното налично БВП тримесечие.

**Само тримесечия с ДВЕТЕ страни налични.** Днес кредитният сток стига едно
тримесечие по-напред от БВП — това тримесечие просто не ражда ratio. Именно
тази забрана е смисълът на модула: сдвояването на най-свеж кредит със застоял
БВП надува съотношението и ускорява привидния му темп.

**Право на отказ.** Липсва ли съставка (празен кеш, счупена заявка, нула общи
тримесечия) — серията просто НЕ СЕ РАЖДА. Без изключение, без warning-шум и
най-вече без фалшив ред: липсващо наблюдение е по-честно от изчислено от
половин рецепта.

──────────────────────────────────────────────────────────────────────────────
РЕВИЗИОННА ИСТОРИЯ — защо тази серия изобщо съществува (мандат №54 §0б)
──────────────────────────────────────────────────────────────────────────────
До 29.07.2026 числата за кредит/БВП в хипотезния блок идваха от РЪЧНА сверка с
дата. Живата, тримесечно изравнена конвенция ги ревизира надолу: днешното ниво е
ОКОЛО това от 2008 и ПОД цикличния връх от кризата (свит знаменател), а темпът и
разривът спрямо номиналния ръст са по-малки от ръчните. Вероятната причина е
точно сдвояването отгоре — най-свежият кредитен сток срещу по-стар БВП.

Следствие за разказа, записано тук, за да не се преоткрива: ливъриджната
хипотеза губи най-острата си реплика (днес не сме над върха от кризата), но
пази посоката — съотношението се качва и изпреварва номиналния ръст. Двете
хипотези остават РАВНОСТОЙНИ; уредът не отсъжда коя е причината.
"""
from __future__ import annotations

import logging
from typing import Optional

import pandas as pd

logger = logging.getLogger(__name__)

# Каталожният ключ на изведената серия + двете ѝ съставки.
CREDIT_GDP_HH = "BG_CREDIT_GDP_HH"
CREDIT_STOCK_KEY = "BG_LOANS_HH"
NGDP_KEY = "BG_NGDP"

# Колко тримесечия се сумират, за да стане потокът годишен.
GDP_SUM_QUARTERS = 4


def _to_quarterly_periods(s: Optional[pd.Series]) -> Optional[pd.Series]:
    """Времева серия → серия по тримесечен ПЕРИОД (индекс `PeriodIndex[Q]`).

    Изравняването по период е това, което позволява на двете датови конвенции
    (край срещу начало на тримесечие) да се срещнат честно. Дубликат в един
    период е дефект на входа, не нещо за мълчаливо усредняване — тогава
    серията не се ражда.
    """
    if s is None or len(s) == 0:
        return None
    if not isinstance(s.index, pd.DatetimeIndex):
        return None
    clean = s.dropna().sort_index()
    if clean.empty:
        return None
    out = pd.Series(clean.values, index=clean.index.to_period("Q"), dtype="float64")
    if out.index.has_duplicates:
        return None
    return out


def credit_to_gdp(
    credit_stock: Optional[pd.Series],
    ngdp: Optional[pd.Series],
    *,
    quarters: int = GDP_SUM_QUARTERS,
) -> Optional[pd.Series]:
    """Кредитен СТОК ÷ 4-тримесечна СУМА на номиналния БВП × 100.

    Връща тримесечна серия в проценти (индексът е ден 1 на ПЪРВИЯ месец на
    тримесечието — Eurostat конвенцията) или None, ако рецептата не е пълна.
    """
    stock_q = _to_quarterly_periods(credit_stock)
    gdp_q = _to_quarterly_periods(ngdp)
    if stock_q is None or gdp_q is None:
        return None

    # Сумата иска ПЪЛНИ 4 тримесечия — `min_periods` по подразбиране е
    # прозорецът, така че непълното начало пада само.
    gdp_sum = gdp_q.rolling(quarters).sum()
    gdp_sum = gdp_sum[gdp_sum > 0].dropna()
    if gdp_sum.empty:
        return None

    common = stock_q.index.intersection(gdp_sum.index)
    if len(common) == 0:
        return None

    ratio = (stock_q.loc[common] / gdp_sum.loc[common] * 100.0).sort_index()
    ratio.index = ratio.index.to_timestamp(how="start")
    ratio.name = CREDIT_GDP_HH
    return ratio


def derive_series(snapshot: dict[str, pd.Series]) -> dict[str, pd.Series]:
    """Дописва изведените серии в снапшота. Викa се СЛЕД `splice_loans`.

    Мутира и връща същия речник (прецедентът е `splice_loans`), за да получат
    всички консуматори — `--status`, лицето, context експортът — едно и също
    число от едно място.
    """
    ratio = credit_to_gdp(snapshot.get(CREDIT_STOCK_KEY), snapshot.get(NGDP_KEY))
    if ratio is None or ratio.empty:
        logger.warning(
            "%s: липсва съставка (%s или %s) — изведената серия не се ражда.",
            CREDIT_GDP_HH, CREDIT_STOCK_KEY, NGDP_KEY,
        )
        snapshot.pop(CREDIT_GDP_HH, None)
        return snapshot

    snapshot[CREDIT_GDP_HH] = ratio
    logger.info(
        "%s: %d тримесечия %s → %s (%s ÷ %d-тримесечна сума на %s)",
        CREDIT_GDP_HH, len(ratio), ratio.index[0].date(), ratio.index[-1].date(),
        CREDIT_STOCK_KEY, GDP_SUM_QUARTERS, NGDP_KEY,
    )
    return snapshot
